		Rwenzori Airlines started as a small airline carrier in 1989 to facilitate air travel between Uganda and the Democratic Republic of Congo. This airline was to facilitate transportation of cargo
 
Between the two countries. The airline was originally designed to handle small number of customers. In 1999 Rwenzori Airline was transformed into an International Airline facilitating travel of tens of thousands of passengers on a daily basis. Today Rwenzori Airlines still use a manual system of flight booking, flight management and scheduling. Flight booking is done through travel agents across major towns, flight data and customer details are kept in manual files. This system is slow and results into booking conflicts, vacant seats in some planes and it is hard to quickly obtain customer information in case of emergency. It’s for this reason, the researcher set out to design an online airline reservation system to provides a modern, flexible reservation and inventory management solutions including call Centre, travel agency, internet engine, global distribution systems and interlines booking with case study of Rwenzori Airlines

